#!/usr/bin/env python3
"""render-d1.py — resolve the per-user application roles from the Profiles and
emit idempotent SQL that syncs them into the fop-rbac Cloudflare D1 database.

This is the D1 counterpart of the KV materialization in terraform/kv.tf. Because
the Cloudflare Terraform provider cannot write D1 rows, CI applies this SQL with
`wrangler d1 execute` (see .github/workflows/sync-rbac-d1.yml). Consumers (e.g.
leave-tracker) read it read-only at runtime, so role changes never require the
app to redeploy.

    python3 scripts/render-d1.py            # -> build/rbac.sql (+ a summary)

Strongest-wins resolution matches terraform/locals.tf (local.user_app_roles) and
the KV docs (local.app_rbac_docs): highest index in the app's ORDERED vocabulary
across every role the user holds, with defaultRole as a floor.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from validate import load_all, load_applications  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "build" / "rbac.sql"


def sql_str(s: str) -> str:
    return "'" + str(s).replace("'", "''") + "'"


def resolve_rows():
    _catalog, roles, users = load_all()
    registry = (load_applications() or {}).get("applications") or {}
    rows = []  # (email, app, role, kind)
    for _uname, u in sorted(users.items()):
        email = u["identity"]["email"].strip().lower()
        rs = u["roles"]
        for aid, app in registry.items():
            idxs = [app["roles"].index(roles[r]["appRoles"][aid]) for r in rs
                    if aid in (roles[r].get("appRoles") or {})]
            if app.get("defaultRole"):
                idxs.append(app["roles"].index(app["defaultRole"]))
            if idxs:
                rows.append((email, aid, app["roles"][max(idxs)], app["kind"]))
    return sorted(rows)


SCHEMA = """CREATE TABLE IF NOT EXISTS app_role (
  email TEXT NOT NULL,
  app   TEXT NOT NULL,
  role  TEXT NOT NULL,
  kind  TEXT NOT NULL,
  PRIMARY KEY (email, app)
);
CREATE INDEX IF NOT EXISTS idx_app_role_email ON app_role(email);"""


def render_sql(rows):
    # NOTE: no BEGIN/COMMIT — D1 rejects explicit SQL transactions. Atomicity
    # comes from `wrangler d1 execute --file` itself: a failed execution rolls
    # the DB back to its original state, so the DELETE+INSERT refresh is safe.
    lines = [
        "-- GENERATED by scripts/render-d1.py — do not edit by hand.",
        "-- Full refresh: replaces every row, so removed roles (offboarding,",
        "-- role changes) are deleted, not just upserted.",
        SCHEMA,
        "DELETE FROM app_role;",
    ]
    if rows:
        values = ",\n".join(
            f"  ({sql_str(e)}, {sql_str(a)}, {sql_str(r)}, {sql_str(k)})"
            for e, a, r, k in rows
        )
        lines.append("INSERT INTO app_role (email, app, role, kind) VALUES\n" + values + ";")
    return "\n".join(lines) + "\n"


def main():
    rows = resolve_rows()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render_sql(rows))
    users = len({r[0] for r in rows})
    apps = sorted({r[1] for r in rows})
    print(f"wrote {OUT}  ({len(rows)} (email,app,role) rows · {users} users · apps: {', '.join(apps)})")
    # show the leave-tracker admins/approvers as a quick sanity check
    lt = [(e, r) for e, a, r, _ in rows if a == "leave-tracker" and r in ("approver", "admin")]
    if lt:
        print("leave-tracker approver/admin:")
        for e, r in lt:
            print(f"  {r:9} {e}")


if __name__ == "__main__":
    main()
